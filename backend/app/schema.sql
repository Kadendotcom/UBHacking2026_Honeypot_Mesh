-- Collector database schema.
-- Safe to run on every startup: IF NOT EXISTS leaves existing tables alone.
-- Timestamps are TEXT in ISO-8601 UTC ("2026-11-07T17:40:00Z") so they sort
-- correctly as plain strings and need no date parsing.

-- One row per attacker connection to a honeypot.
CREATE TABLE IF NOT EXISTS sessions (
    id           TEXT PRIMARY KEY,       -- generated by the honeypot (uuid4)
    src_ip       TEXT,
    country      TEXT,                   -- 2-letter code; NULL until GeoIP is added
    protocol     TEXT,                   -- "ssh" or "http"
    node_id      TEXT,                   -- which honeypot was hit
    started_at   TEXT,
    last_seen_at TEXT,                   -- bumped every event; finds idle sessions
    ended_at     TEXT,                   -- NULL while still active
    status       TEXT DEFAULT 'active',  -- "active" or "closed"
    event_count  INTEGER DEFAULT 0,
    cluster_id   TEXT                    -- NULL until the ML classifies it
);

-- One row per login, command or logout.
-- Command and response share ONE row; the API splits them into the separate
-- "input" and "output" events the frontend wants.
CREATE TABLE IF NOT EXISTS events (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,  -- also the live-feed cursor
    session_id TEXT,
    ts         TEXT,
    type       TEXT,    -- "login", "command" or "logout"
    username   TEXT,
    password   TEXT,
    command    TEXT,    -- NULL for login/logout
    response   TEXT     -- what the honeypot sent back
);

-- Indicators of compromise pulled out of command text.
-- UNIQUE stops the same indicator being stored twice for one session.
CREATE TABLE IF NOT EXISTS iocs (
    id         INTEGER PRIMARY KEY AUTOINCREMENT,
    session_id TEXT,
    type       TEXT,    -- "ip", "domain", "url", "hash", "file_path"
    value      TEXT,
    first_seen TEXT,
    UNIQUE (session_id, type, value)
);

-- Attacker archetypes. Person 3 (ML) owns the contents.
CREATE TABLE IF NOT EXISTS clusters (
    id         TEXT PRIMARY KEY,   -- "c1", "c2", ...
    name       TEXT,               -- display name, e.g. "Mirai Nebula"
    label      TEXT,               -- plain description, e.g. "IoT botnet dropper"
    summary    TEXT,               -- 1-3 sentences
    first_seen TEXT,
    last_seen  TEXT
);

-- Indexes make the two most common lookups fast.
CREATE INDEX IF NOT EXISTS idx_events_session ON events(session_id, id);
CREATE INDEX IF NOT EXISTS idx_sessions_started ON sessions(started_at);
